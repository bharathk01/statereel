"""Regenerate COMPATIBILITY.md and the viewer's "verified against" table from real captures.

Reads tests/fixtures/real/*/manifest.json. Run after any capture:
    python tools/update_compat.py
The viewer block lives between /*<<<VERIFIED_START>>>*/ and /*<<<VERIFIED_END>>>*/.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
REAL = ROOT / "tests" / "fixtures" / "real"
VIEWER = ROOT / "statereel.html"
COMPAT = ROOT / "COMPATIBILITY.md"

# formats with hand-built fixtures only; listed so the table is honest about what is not
# backed by a real capture yet
FIXTURE_ONLY = [
    # (manifest key, framework, format, adapter) - rows drop out once a real capture exists
    ("claude_agent_sdk", "Claude Agent SDK", "stream-json NDJSON, Python dataclass reprs", "ndjson-events, repr-stream"),
    ("google_adk", "Google ADK", "Event(...) reprs", "repr-stream"),
    ("crewai", "CrewAI", "verbose console", "crewai-console"),
    ("autogen", "Microsoft AutoGen", "Console() output, message reprs", "autogen-console"),
    ("pydantic_ai", "Pydantic AI", "message history reprs", "python-literal"),
    ("llamaindex", "LlamaIndex", "AgentWorkflow event reprs", "repr-stream"),
    ("semantic_kernel", "Semantic Kernel", "ChatMessageContent reprs", "repr-stream"),
    ("vercel_ai_sdk", "Vercel AI SDK", "generateText steps JSON", "json"),
    ("smolagents", "smolagents", "console ReAct trace", "react-console"),
    ("strands", "AWS Strands", "message JSON lines", "ndjson-events"),
]


def load_manifests():
    out = []
    for m in sorted(REAL.glob("*/manifest.json")):
        data = json.loads(m.read_text(encoding="utf-8"))
        data["_dir"] = m.parent.name
        out.append(data)
    return out


def verified_table(manifests):
    """adapter name -> provenance shown in the viewer's diagnostics. Several frameworks can
    share one adapter (repr-stream reads ADK, Claude SDK and Pydantic AI), so list them all."""
    seen = {}
    for man in manifests:
        main_pkg, main_ver = next(iter(man["versions"].items()))
        label = f"{man['framework']} ({main_pkg} {main_ver})"
        for fx in man["fixtures"].values():
            seen.setdefault(fx["adapter"], [])
            if label not in seen[fx["adapter"]]:
                seen[fx["adapter"]].append(label)
    dates = sorted({m["captured_at"] for m in manifests})
    when = dates[-1] if dates else ""
    return {a: ", ".join(v) + f" - real captures, {when}" for a, v in sorted(seen.items())}


def write_viewer_block(table):
    html = VIEWER.read_text(encoding="utf-8")
    block = ("/*<<<VERIFIED_START>>>*/\n"
             "// generated by tools/update_compat.py from tests/fixtures/real/*/manifest.json - do not edit\n"
             "var ADAPTER_VERIFIED = " + json.dumps(table, indent=2, ensure_ascii=False) + ";\n"
             "/*<<<VERIFIED_END>>>*/")
    pattern = re.compile(r"/\*<<<VERIFIED_START>>>\*/.*?/\*<<<VERIFIED_END>>>\*/", re.S)
    if not pattern.search(html):
        raise SystemExit("VERIFIED markers not found in the viewer")
    VIEWER.write_text(pattern.sub(lambda _: block, html), encoding="utf-8")


def write_compat(manifests):
    lines = [
        "# Compatibility",
        "",
        "Generated by `tools/update_compat.py`. Do not edit by hand.",
        "",
        "## Verified with real captures",
        "",
        "Each row is produced by running a scripted agent (fake model, no API key) on the listed",
        "versions and printing its output the way developers do. `tests/real.test.js` checks the",
        "viewer recovers the same run from every print style.",
        "",
        "| Framework | Versions | Captured | Print styles covered |",
        "|---|---|---|---|",
    ]
    for man in manifests:
        ver = ", ".join(f"`{k} {v}`" for k, v in man["versions"].items())
        styles = ", ".join(f"`{f.removesuffix('.log')}`" for f in man["fixtures"])
        lines.append(f"| {man['framework']} | {ver} | {man['captured_at']} | {styles} |")
    lines += [
        "",
        "Scale: `tests/scale.js` replicates every capture into files holding 10, 100 and 500 runs and",
        "checks tool calls, pairing, failures and model calls stay exact.",
    ]
    lines += [
        "",
        "## Supported from documented formats (no real capture yet)",
        "",
        "Parsed from fixtures built against each framework's docs or source. They work, but are not",
        "yet pinned to a version. Contributions of real captures are welcome.",
        "",
        "| Framework | Format | Adapter |",
        "|---|---|---|",
    ]
    captured = {m.get("key") for m in manifests}
    lines += [f"| {fw} | {fmt} | `{ad}` |" for key, fw, fmt, ad in FIXTURE_ONLY if key not in captured]
    lines += [
        "",
        "## When a framework changes its log format",
        "",
        "1. The weekly `compat` workflow re-captures against the latest releases. A failing",
        "   `tests/real.test.js` row names the fixture and the field that changed.",
        "2. The viewer's *State & diagnostics* tab lists any **unrecognised types** it met. That is",
        "   usually the new message or block type.",
        "3. Teach the parser the new name: add it to `KIND_BY_TYPE` / `MSGISH`, a field alias to",
        "   `pick(...)`, or a block type to `absorbParts`. Keep the old names, since older versions",
        "   are still in use.",
        "4. Re-capture, run `python tools/update_compat.py`, and commit the new fixtures together",
        "   with the parser change, so both versions stay tested.",
        "",
    ]
    COMPAT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    mans = load_manifests()
    table = verified_table(mans)
    write_viewer_block(table)
    write_compat(mans)
    print(f"{len(mans)} manifest(s) -> COMPATIBILITY.md + viewer block ({len(table)} adapter(s) verified)")
